function poolForLabel(label: string): string[] {
  if (POOL[label]) return POOL[label]
  const base = label.replace(/（\d+）$/, '').replace(/\(\d+\)$/, '')
  return POOL[base] ?? []
}

/** 畫面上要列的候選：快照有就用快照；舊資料用 mock 同一組可能值補上。 */
export function candidatesForField(field: {
  label: string
  value: string
  candidates?: string[]
}): string[] {
  const stored = (field.candidates ?? []).map((item) => item.trim()).filter(Boolean)
  const current = field.value.trim()
  if (stored.length >= 2) {
    return [...new Set([current, ...stored].filter(Boolean))]
  }
  const pool = poolForLabel(field.label)
  if (pool.length < 2) return stored
  return [...new Set([current, ...pool].filter(Boolean))].slice(0, 4)
}
